# Delcare Tuple
fruits =("Mango","Orange","Apple","Banna","Kiwi","Pineapple","watermelon")
# Read Elements
print(fruits)
print("---------")
# Read Elements using Loops
for i in range(0, len(fruits)):
    print(fruits[i])
print("---------")
# Read Elements suing for Each
for element in fruits:
    print(element)