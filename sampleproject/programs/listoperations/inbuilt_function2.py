# Reverse : It reverse the elements
cities=["Boston","Mysore","California","Sanjose","New york","Bangalore"]
cities.reverse()
print(cities)
print("----------------")
# sort: It sorts the Elements
cities=["Boston","Mysore","California","Sanjose","New york","Bangalore"]
cities.sort()
print(cities)
print("----------------")
# copy : It copies the list
cities=["Boston","Mysore","California","Sanjose","New york","Bangalore"]
x=cities.copy()
print(x)
print("----------------")
# index : It provides position based on element
cities=["Boston","Mysore","California","Sanjose","New york","Bangalore"]
print(cities.index("California"))
print("----------------")
# clear : It clears the list
cities=["Boston","Mysore","California","Sanjose","New york","Bangalore"]
cities.clear()
print(cities)
